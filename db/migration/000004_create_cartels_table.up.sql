CREATE TABLE IF NOT EXISTS cartels (
    id VARCHAR PRIMARY KEY,
    contender_id VARCHAR NOT NULL UNIQUE REFERENCES contenders(id),
    wins INTEGER NOT NULL,
    losses INTEGER NOT NULL,
    draws INTEGER NOT NULL,
    no_contests INTEGER NOT NULL,
    wins_by_ko INTEGER NOT NULL,
    wins_by_tko INTEGER NOT NULL,
    wins_by_sub INTEGER NOT NULL,
    wins_by_dec INTEGER NOT NULL,
    losses_by_ko INTEGER NOT NULL,
    losses_by_tko INTEGER NOT NULL,
    losses_by_sub INTEGER NOT NULL,
    losses_by_dec INTEGER NOT NULL,
    total_fights INTEGER NOT NULL,
    avg_performance_rating INTEGER NULL,
    last_fight_date TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT NULL,
    deleted_at TIMESTAMPTZ DEFAULT NULL
);
